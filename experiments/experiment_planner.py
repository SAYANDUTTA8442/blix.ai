"""
Experiment Planner — Blix v0.3.13  (New module 3, "Curiosity + Active Experimentation")

Converts curiosity into action:

    CuriositySignal
      ↓
    Hypothesis
      ↓
    Experiment(actions, expected_result, success_criteria)
      ↓
    Observation
      ↓
    HypothesisManager.add_evidence()
      ↓
    BeliefStore.confirm_observation()  (if SUPPORTED)

An Experiment is a structured plan for testing one Hypothesis —
specific actions to take, a predicted result, and measurable success
criteria. When the experiment is run and an outcome is recorded via
``record_outcome()``, the result propagates to ``HypothesisManager``
(updating the hypothesis confidence) and, if the hypothesis reaches
SUPPORTED, the outcome promotes to an OBSERVED belief directly.

This is "science" in the sense the spec names: structured
observation, not introspection. No RL, no reward shaping — just
a data structure for "here is what I'll test, here is what I expect,
here is what happened."

Python 3.10 compatible.
"""

from __future__ import annotations

import json
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Optional

from causality.epistemic_status import EpistemicStatus
from curiosity.curiosity_engine import CuriositySignal
from utils.logger import get_logger

log = get_logger(__name__)


class ExperimentStatus(str, Enum):
    PLANNED = "planned"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


@dataclass
class Experiment:
    """A structured plan for testing one hypothesis."""

    hypothesis_id: str
    actions: list[str]                    # concrete steps to execute
    expected_result: str                  # what success looks like
    success_criteria: list[str]           # measurable criteria
    curiosity_signal_target: str = ""     # the CuriositySignal.target that motivated this
    status: ExperimentStatus = ExperimentStatus.PLANNED
    epistemic_status: EpistemicStatus = EpistemicStatus.PREDICTED  # the expected outcome is a prediction
    experiment_id: str = field(default_factory=lambda: uuid.uuid4().hex[:10])
    outcome: Optional[str] = None
    outcome_confirmed: bool = False       # True once the outcome updates the hypothesis/belief
    planned_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    completed_at: Optional[str] = None

    def to_dict(self) -> dict:
        return {
            "experiment_id": self.experiment_id, "hypothesis_id": self.hypothesis_id,
            "actions": self.actions, "expected_result": self.expected_result,
            "success_criteria": self.success_criteria,
            "curiosity_signal_target": self.curiosity_signal_target,
            "status": self.status.value, "epistemic_status": self.epistemic_status.value,
            "outcome": self.outcome, "outcome_confirmed": self.outcome_confirmed,
            "planned_at": self.planned_at, "completed_at": self.completed_at,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "Experiment":
        return cls(
            hypothesis_id=d["hypothesis_id"], actions=d.get("actions", []),
            expected_result=d.get("expected_result", ""), success_criteria=d.get("success_criteria", []),
            curiosity_signal_target=d.get("curiosity_signal_target", ""),
            status=ExperimentStatus(d.get("status", "planned")),
            epistemic_status=EpistemicStatus(d.get("epistemic_status", EpistemicStatus.PREDICTED.value)),
            experiment_id=d.get("experiment_id", uuid.uuid4().hex[:10]),
            outcome=d.get("outcome"), outcome_confirmed=d.get("outcome_confirmed", False),
            planned_at=d.get("planned_at", ""), completed_at=d.get("completed_at"),
        )


class ExperimentPlanner:
    """
    Plans and tracks experiments that test hypotheses generated by
    ``HypothesisManager`` in response to ``CuriosityEngine`` signals.

    Parameters
    ----------
    experiment_file:
        Path to ``experiments.json``.
    hypothesis_manager:
        ``HypothesisManager`` — experiments link to and update hypotheses.
    """

    def __init__(self, experiment_file: Path, hypothesis_manager) -> None:
        self._file = experiment_file
        self._hypothesis_manager = hypothesis_manager
        self._experiments: dict[str, Experiment] = {}
        self._load()

    # ------------------------------------------------------------------
    # Persistence
    # ------------------------------------------------------------------

    def _load(self) -> None:
        if not self._file.exists():
            return
        try:
            with self._file.open("r", encoding="utf-8") as fh:
                raw = json.load(fh)
            for item in raw:
                e = Experiment.from_dict(item)
                self._experiments[e.experiment_id] = e
        except Exception as exc:
            log.warning("ExperimentPlanner: load failed (%s)", exc)

    def _save(self) -> None:
        self._file.parent.mkdir(parents=True, exist_ok=True)
        with self._file.open("w", encoding="utf-8") as fh:
            json.dump([e.to_dict() for e in self._experiments.values()], fh, indent=2, ensure_ascii=False)

    # ------------------------------------------------------------------
    # Planning
    # ------------------------------------------------------------------

    def plan(
        self,
        hypothesis_id: str,
        actions: list[str],
        expected_result: str,
        success_criteria: list[str],
        curiosity_signal: Optional[CuriositySignal] = None,
    ) -> Experiment:
        """Create a new experiment for a given hypothesis."""
        hyp = self._hypothesis_manager.get(hypothesis_id)
        if hyp is None:
            raise ValueError(f"Hypothesis '{hypothesis_id}' not found in HypothesisManager.")

        experiment = Experiment(
            hypothesis_id=hypothesis_id, actions=actions, expected_result=expected_result,
            success_criteria=success_criteria,
            curiosity_signal_target=curiosity_signal.target if curiosity_signal else "",
        )
        self._experiments[experiment.experiment_id] = experiment
        self._hypothesis_manager.link_experiment(hypothesis_id, experiment.experiment_id)
        self._save()
        log.info("ExperimentPlanner: planned experiment %s for hypothesis %s", experiment.experiment_id, hypothesis_id)
        return experiment

    def plan_from_signal(self, signal: CuriositySignal, hypothesis_id: str) -> Experiment:
        """
        Generate a default experiment plan from a CuriositySignal — a
        convenience wrapper that produces reasonable default actions and
        criteria based on the signal's trigger type.
        """
        from curiosity.curiosity_engine import CuriosityTrigger

        trigger = signal.trigger
        if trigger == CuriosityTrigger.LOW_CONFIDENCE:
            actions = [f"Gather additional evidence for: {signal.target[:80]}", "Cross-reference with related beliefs"]
            expected_result = "Confidence increases above 0.5"
            criteria = ["At least 2 new confirming observations", "No new contradicting evidence"]
        elif trigger == CuriosityTrigger.CONTRADICTION:
            actions = ["Identify the source of each conflicting belief", "Seek a third observation to adjudicate"]
            expected_result = "One belief is confirmed, the other deprecated"
            criteria = ["Contradicting belief resolved", "Confidence of surviving belief > 0.6"]
        elif trigger == CuriosityTrigger.SPARSE_EVIDENCE:
            actions = [f"Seek corroborating evidence for: {signal.target[:80]}"]
            expected_result = "Evidence count increases above threshold"
            criteria = ["At least 3 total observations", "Belief confidence > 0.5"]
        elif trigger == CuriosityTrigger.FREQUENT_FAILURES:
            actions = [f"Diagnose root cause of failures in: {signal.target}", "Test alternative approach", "Compare outcomes"]
            expected_result = "Failure rate decreases after diagnosis"
            criteria = ["Root cause identified in CauseGraph", "Failure rate < 50% of baseline"]
        else:  # UNKNOWN_DOMAIN
            actions = [f"Survey existing knowledge about: {signal.target}", "Identify the most uncertain sub-question"]
            expected_result = "At least one new piece of knowledge recorded"
            criteria = ["At least 1 new belief or principle created", "KnowledgeGap severity reduced"]

        return self.plan(hypothesis_id, actions, expected_result, criteria, curiosity_signal=signal)

    # ------------------------------------------------------------------
    # Outcome recording
    # ------------------------------------------------------------------

    def record_outcome(
        self,
        experiment_id: str,
        outcome: str,
        success: bool,
        confidence_delta: Optional[float] = None,
    ) -> Optional[Experiment]:
        """
        Record an experimental outcome. A real observed outcome is
        fed directly into ``HypothesisManager.add_evidence()``, which
        will call ``BeliefStore.confirm_observation()`` if the
        hypothesis reaches the support threshold — no extra gating
        required (per locked architecture: confirmed experiment
        outcomes can promote to OBSERVED directly).
        """
        experiment = self._experiments.get(experiment_id)
        if experiment is None:
            return None

        experiment.outcome = outcome
        experiment.status = ExperimentStatus.COMPLETED
        experiment.outcome_confirmed = True
        experiment.completed_at = datetime.now(timezone.utc).isoformat()
        experiment.epistemic_status = EpistemicStatus.OBSERVED  # it happened; it's real

        # Default confidence delta: modest positive for success, negative for failure
        delta = confidence_delta if confidence_delta is not None else (0.2 if success else -0.1)
        self._hypothesis_manager.add_evidence(experiment.hypothesis_id, f"Experiment {experiment_id}: {outcome}", confidence_delta=delta)

        self._save()
        log.info("ExperimentPlanner: recorded outcome for %s (success=%s)", experiment_id, success)
        return experiment

    # ------------------------------------------------------------------
    # Querying
    # ------------------------------------------------------------------

    def get(self, experiment_id: str) -> Optional[Experiment]:
        return self._experiments.get(experiment_id)

    def planned(self) -> list[Experiment]:
        return [e for e in self._experiments.values() if e.status == ExperimentStatus.PLANNED]

    def completed(self) -> list[Experiment]:
        return [e for e in self._experiments.values() if e.status == ExperimentStatus.COMPLETED]

    def for_hypothesis(self, hypothesis_id: str) -> list[Experiment]:
        return [e for e in self._experiments.values() if e.hypothesis_id == hypothesis_id]

    @property
    def count(self) -> int:
        return len(self._experiments)
